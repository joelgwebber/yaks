//! `yaks release changelog` (yaks-7278): a Keep a Changelog file projected from
//! the release doks, through the real binary on a temp repo with a scratch farm,
//! tags, and (for the links) a GitHub-looking `origin` whose refs are made by
//! hand, so nothing touches the network.

mod common;
use common::Repo;
use std::path::PathBuf;

fn farm(r: &Repo) -> PathBuf {
    PathBuf::from(r.run(&["path"]).trim())
}

/// Where the farm root sits under its branch's top: `""`, or `.yaks/`.
fn prefix(r: &Repo) -> String {
    let root = farm(r);
    match root.file_name() {
        Some(n) if n == ".yaks" => ".yaks/".into(),
        _ => String::new(),
    }
}

fn read(r: &Repo, rel: &str) -> String {
    std::fs::read_to_string(farm(r).join(rel)).unwrap()
}

fn write(r: &Repo, rel: &str, text: &str) {
    std::fs::write(farm(r).join(rel), text).unwrap();
}

fn changelog(r: &Repo, args: &[&str]) -> (String, String) {
    let mut a = vec!["release", "changelog"];
    a.extend(args);
    let out = r.cmd(&a);
    assert!(
        out.status.success(),
        "{a:?}: {}",
        String::from_utf8_lossy(&out.stderr)
    );
    (
        String::from_utf8(out.stdout).unwrap(),
        String::from_utf8(out.stderr).unwrap(),
    )
}

/// `v0.1.0` (no entries), then `v0.2.0` with a feature, a fix and a gap.
fn two_releases(tag: &str) -> (Repo, String, String, String) {
    let r = Repo::new(tag);
    r.commit("initial");
    r.git(&["tag", "v0.1.0"]);
    let feat = r.create("A feature", "feature", None);
    let fix = r.create("A fix", "bug", None);
    let gap = r.create("Gap", "task", None);
    r.run(&["shorn", &feat, "--change", "Adds the feature."]);
    r.run(&["shorn", &fix, "--change", "Fixes the bug."]);
    r.run(&["shorn", &gap]);
    r.commit(&format!("{feat}: the feature"));
    r.commit(&format!("{fix}: the fix"));
    r.commit(&format!("the gap ({gap})"));
    r.git(&["tag", "v0.2.0"]);
    (r, feat, fix, gap)
}

/// Commit the farm and make `origin` (a GitHub URL) hold its branch and the
/// code branch, as a push would.
fn publish(r: &Repo) {
    r.run(&["commit"]);
    let top = farm(r);
    let farm_head = git_in(&top, &["rev-parse", "HEAD"]);
    let branch = git_in(&top, &["symbolic-ref", "--short", "HEAD"]);
    r.git(&["remote", "add", "origin", "https://github.com/o/r.git"]);
    r.git(&[
        "update-ref",
        &format!("refs/remotes/origin/{branch}"),
        &farm_head,
    ]);
    let head = r.git(&["rev-parse", "HEAD"]);
    r.git(&["update-ref", "refs/remotes/origin/main", &head]);
}

fn git_in(dir: &std::path::Path, args: &[&str]) -> String {
    let out = std::process::Command::new("git")
        .args(["-c", "user.name=t", "-c", "user.email=t@t"])
        .arg("-C")
        .arg(dir)
        .args(args)
        .env_remove("GIT_DIR")
        .env_remove("GIT_WORK_TREE")
        .output()
        .unwrap();
    assert!(out.status.success(), "git {args:?}");
    String::from_utf8_lossy(&out.stdout).trim().to_string()
}

#[test]
fn a_tag_with_no_dok_is_generated_and_one_without_entries_says_so() {
    let (r, feat, fix, gap) = two_releases("generated");
    publish(&r);
    let (text, _) = changelog(&r, &[]);
    assert!(text.starts_with("# Changelog\n\nGenerated by `yaks release changelog`"));
    assert!(text.contains("keepachangelog.com"), "{text}");
    // Newest first, no Unreleased (HEAD is the tag).
    let (a, b) = (
        text.find("## [v0.2.0]").unwrap(),
        text.find("## [v0.1.0]").unwrap(),
    );
    assert!(a < b, "{text}");
    assert!(!text.contains("Unreleased"), "{text}");
    // Headed by the tag's date, entries demoted under it, each linking its yak.
    assert!(text.contains("## [v0.2.0] - 20"), "{text}");
    let herd = feat.split('-').next().unwrap();
    let pre = prefix(&r);
    let url = |id: &str| format!("https://github.com/o/r/blob/yaks/{pre}{herd}/yaks/{id}.md");
    assert!(
        text.contains("### Added\n\n- Adds the feature. (["),
        "{text}"
    );
    assert!(
        text.contains(&format!("([{feat}]({}))", url(&feat))),
        "{text}"
    );
    assert!(
        text.contains(&format!("([{fix}]({}))", url(&fix))),
        "{text}"
    );
    assert!(text.contains("### Fixed\n"), "{text}");
    assert!(
        text.contains(&format!("### Not described\n\n- Gap ([{gap}]")),
        "{text}"
    );
    assert!(!text.contains("](/"), "a farm link was left: {text}");
    assert!(text.contains("## [v0.1.0] - 20"), "{text}");
    assert!(
        text.trim_end().ends_with("No change lines recorded."),
        "{text}"
    );
}

#[test]
fn a_release_dok_is_used_with_markers_and_title_gone_and_headings_demoted() {
    let (r, feat, ..) = two_releases("dok");
    r.run(&["release", "dok", "v0.2.0"]);
    let dok = read(&r, "doks/releases/v0.2.0.md");
    let dok = dok.replace(
        "<!-- Headlines: what matters in this release, with a screenshot if there is one (pin images with @<sha>). -->",
        "The headline is [the design](/doks/design.md).",
    );
    write(&r, "doks/releases/v0.2.0.md", &dok);
    r.run(&["dok", "new", "doks/design.md", "--body", "# Design\n"]);
    publish(&r);
    let (text, err) = changelog(&r, &[]);
    assert_eq!(err, "", "{err}");
    let section = &text[text.find("## [v0.2.0]").unwrap()..text.find("## [v0.1.0]").unwrap()];
    assert!(
        section.contains(&format!("\n\nThe headline is [the design](https://github.com/o/r/blob/yaks/{}doks/design.md).\n\n### Added\n\n- Adds the feature.", prefix(&r))),
        "{section}"
    );
    for gone in ["<!--", "# yak v0.2.0", "\n## Added", "Headlines"] {
        assert!(!section.contains(gone), "{gone:?} in {section}");
    }
    assert!(section.contains(&feat));
    // Nothing is written to the farm.
    assert_eq!(read(&r, "doks/releases/v0.2.0.md"), dok);
}

#[test]
fn a_yanked_release_is_marked() {
    let (r, ..) = two_releases("yanked");
    r.run(&["release", "dok", "v0.2.0"]);
    let dok = read(&r, "doks/releases/v0.2.0.md").replacen(
        "type: release\n",
        "type: release\nyanked: true\n",
        1,
    );
    write(&r, "doks/releases/v0.2.0.md", &dok);
    let (text, _) = changelog(&r, &[]);
    let head = text.lines().find(|l| l.starts_with("## [v0.2.0]")).unwrap();
    assert!(head.ends_with(" [YANKED]"), "{head}");
    // Only the yanked release is marked.
    assert_eq!(text.matches("[YANKED]").count(), 1, "{text}");
}

#[test]
fn commits_after_the_last_tag_make_an_unreleased_section() {
    let (r, ..) = two_releases("unreleased");
    let (text, _) = changelog(&r, &[]);
    assert!(!text.contains("[Unreleased]"), "{text}");
    let more = r.create("More", "feature", None);
    r.run(&["shorn", &more, "--change", "Adds more."]);
    r.commit(&format!("{more}: more"));
    let (text, _) = changelog(&r, &[]);
    let (u, v) = (
        text.find("## [Unreleased]\n").unwrap(),
        text.find("## [v0.2.0]").unwrap(),
    );
    assert!(u < v, "{text}");
    assert!(text[u..v].contains("- Adds more."), "{text}");
    assert!(!text[u..v].contains("Adds the feature"), "{text}");
}

#[test]
fn an_untagged_release_dok_ending_at_head_leads_as_unreleased() {
    let (r, ..) = two_releases("untagged");
    let more = r.create("More", "feature", None);
    r.run(&["shorn", &more, "--change", "Adds more."]);
    r.commit(&format!("{more}: more"));
    r.run(&["release", "dok", "v0.3.0"]);
    let (text, _) = changelog(&r, &[]);
    assert!(text.contains("## [v0.3.0] - Unreleased\n"), "{text}");
    assert!(!text.contains("## [Unreleased]"), "{text}");
    let (one, _) = changelog(&r, &["--release", "v0.3.0"]);
    assert!(one.starts_with("## [v0.3.0] - Unreleased\n"), "{one}");
    // Once it is tagged it is an ordinary release with the tag's date.
    r.git(&["tag", "v0.3.0"]);
    let (text, _) = changelog(&r, &[]);
    assert!(text.contains("## [v0.3.0] - 20"), "{text}");
}

#[test]
fn release_prints_one_section_without_the_header() {
    let (r, ..) = two_releases("one");
    let (one, _) = changelog(&r, &["--release", "v0.2.0"]);
    assert!(one.starts_with("## [v0.2.0] - 20"), "{one}");
    assert!(
        !one.contains("# Changelog") && !one.contains("v0.1.0"),
        "{one}"
    );
    let out = r.cmd(&["release", "changelog", "--release", "v9.9.9"]);
    assert!(!out.status.success());
    let err = String::from_utf8_lossy(&out.stderr);
    assert!(
        err.contains("v9.9.9: not a release") && err.contains("v0.2.0"),
        "{err}"
    );
}

#[test]
fn output_writes_a_file_and_prints_nothing_of_it() {
    let (r, ..) = two_releases("out");
    let out = r.run(&["release", "changelog", "-o", "CHANGELOG.md"]);
    assert!(out.starts_with("Wrote CHANGELOG.md (2 releases)"), "{out}");
    let file = std::fs::read_to_string(r.dir.join("CHANGELOG.md")).unwrap();
    assert!(file.starts_with("# Changelog\n"), "{file}");
}

#[test]
fn only_tags_the_branch_reaches_appear() {
    let (r, ..) = two_releases("branch");
    r.git(&["checkout", "-q", "-b", "side", "v0.1.0"]);
    r.commit_in("g.txt", "side work");
    r.git(&["tag", "v0.9.0"]);
    r.git(&["checkout", "-q", "main"]);
    let (text, _) = changelog(&r, &[]);
    assert!(
        text.contains("## [v0.2.0]") && !text.contains("v0.9.0"),
        "{text}"
    );
}

#[test]
fn links_drop_to_text_with_one_note_when_there_is_no_remote() {
    let (r, feat, ..) = two_releases("noremote");
    let (text, err) = changelog(&r, &[]);
    assert!(
        text.contains(&format!("- Adds the feature. ({feat})")),
        "{text}"
    );
    let body = &text[text.find("## [").unwrap()..];
    assert!(!body.contains("]("), "{body}");
    assert_eq!(err.matches("note:").count(), 1, "{err}");
    assert!(
        err.contains("plain text") && err.contains("no remote"),
        "{err}"
    );
}

#[test]
fn a_pinned_image_becomes_the_hosts_raw_url_and_links_keep_working() {
    let (r, ..) = two_releases("image");
    r.run(&["release", "dok", "v0.2.0"]);
    r.run(&["dok", "new", "doks/shot.md", "--body", "# Shot\n"]);
    std::fs::write(farm(&r).join("doks/shot.png"), "png").unwrap();
    r.run(&["commit"]);
    let pin = git_in(&farm(&r), &["rev-parse", "HEAD"]);
    let dok = read(&r, "doks/releases/v0.2.0.md").replace(
        "<!-- Headlines: what matters in this release, with a screenshot if there is one (pin images with @<sha>). -->",
        &format!("![the shot](/doks/shot.png@{pin})"),
    );
    write(&r, "doks/releases/v0.2.0.md", &dok);
    publish(&r);
    let (text, _) = changelog(&r, &[]);
    assert!(
        text.contains(&format!(
            "![the shot](https://github.com/o/r/raw/{pin}/{}doks/shot.png)",
            prefix(&r)
        )),
        "{text}"
    );
    assert!(!text.contains("raw.githubusercontent"), "{text}");
}

#[test]
fn links_drop_to_text_when_the_farm_branch_is_not_on_the_remote() {
    let (r, feat, ..) = two_releases("unpublished");
    r.run(&["commit"]);
    // A remote with the code branch but not the farm branch.
    r.git(&["remote", "add", "origin", "https://github.com/o/r.git"]);
    let head = r.git(&["rev-parse", "HEAD"]);
    r.git(&["update-ref", "refs/remotes/origin/main", &head]);
    let (text, err) = changelog(&r, &[]);
    assert!(
        text.contains(&format!("- Adds the feature. ({feat})")),
        "{text}"
    );
    assert!(!text[text.find("## [").unwrap()..].contains("]("), "{text}");
    assert_eq!(err.matches("note:").count(), 1, "{err}");
    assert!(err.contains("not on origin"), "{err}");
}

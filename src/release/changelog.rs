//! `yaks release changelog` (yaks-7278, design `/doks/design/changelog.md` §5):
//! a Keep a Changelog file for the checked-out branch, projected from the
//! farm's release doks and never stored in the farm.
//!
//! The releases are the release tags `HEAD` reaches (newest version first),
//! plus an `Unreleased` section (or, once its release dok exists, that
//! version marked unreleased). A release with a dok is its dok: the headline
//! prose and the block, minus the title, the markers and the headline
//! placeholder, headings pushed down one level. One without a dok is the
//! entries [`super::entries`] would put in one, so every release appears.
//!
//! Links into the farm leave as web URLs, through the one seam `yaks url`
//! uses ([`Space::web_url`]); a link it cannot give is written as its text.
//! An image comes out as the host's raw file URL, which serves Git LFS
//! content ([`hosting::Repo::raw_url`]).


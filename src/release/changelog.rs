/// Everything the projection needs to turn a farm link into a web URL, and
/// what it could not.
struct Cx {
    space: Space,
    ids: HashSet<String>,
    /// The host of the farm branch and of the code checkout, for raw image
    /// URLs (they differ when `yaks.farm` shares another repo's farm).
    farm_host: Option<hosting::Repo>,
    /// Why links to the farm's living files cannot be given: its branch is
    /// not on the remote (a fallback to a commit permalink would pin them).
    farm_unpublished: Option<String>,
    code_host: Option<hosting::Repo>,
    tasks: Option<Vec<Task>>,
    /// A link's outcome by its normalized destination and whether it is an
    /// image: one release dok links the same yak many times.
    seen: HashMap<(String, bool), Option<String>>,
    /// Why links were written as text.
    dropped: Vec<String>,
    /// What `web_url` said about links it kept (not pushed yet).
    leads_nowhere: Vec<String>,
}

impl Cx {
    fn new(farm: &Farm, repo: &Path) -> Cx {
        let mut farm_host = None;
        let mut farm_unpublished = None;
        if let Some(g) = store::farm_git(farm.root())
            && let Ok((remote, host)) = gitrepo::hosting_repo(&g.top, Some(&g.branch))
        {
            if !gitrepo::remote_branch_exists(&g.top, &remote, &g.branch) {
                farm_unpublished = Some(format!(
                    "the farm branch {} is not on {remote} as last fetched (`yaks sync` publishes it)",
                    g.branch
                ));
            }
            farm_host = Some(host);
        }
        let code_host = gitrepo::hosting_repo(repo, gitrepo::current_branch(repo).as_deref())
            .ok()
            .map(|(_, r)| r);
        Cx {
            space: Space::new(farm.root(), Some(repo.to_path_buf())),
            ids: store::all_ids(farm.root()),
            farm_host,
            farm_unpublished,
            code_host,
            tasks: None,
            seen: HashMap::new(),
            dropped: Vec::new(),
            leads_nowhere: Vec::new(),
        }
    }

    /// The host URL of a link, or why there is none. An image is asked for
    /// at a commit and returned as the host's raw file URL.
    fn url(&mut self, place: &Place, image: bool) -> Result<String> {
        let living = match place {
            Place::Yak { .. } | Place::Attachment { .. } | Place::FarmDir { .. } => true,
            Place::FarmFile { rev, .. } => rev.is_none(),
            _ => false,
        };
        if living && let Some(why) = &self.farm_unpublished {
            bail!("{why}");
        }
        let web = self.space.web_url(place, image)?;
        if let Some(n) = web.note {
            self.leads_nowhere.push(n);
        }
        if image {
            let host = match place {
                Place::CodeFile { .. } | Place::Commit { .. } => &self.code_host,
                _ => &self.farm_host,
            };
            if let Some(host) = host
                && let Some(hosting::HostRef::File { commit, path, .. }) = host.parse_url(&web.url)
            {
                return Ok(host.raw_url(&commit, &path));
            }
        }
        Ok(web.url)
    }

    fn fate(&mut self, dest: &str, image: bool, from: links::From) -> Fate {
        let link = links::parse(dest, from, |t| self.ids.contains(t));
        if matches!(link, Link::Url(_) | Link::Local(_) | Link::Upward(_)) {
            return Fate::Keep;
        }
        let key = (links::dest(&link).unwrap_or_default(), image);
        if let Some(known) = self.seen.get(&key) {
            return match known {
                Some(u) => Fate::Url(u.clone()),
                None => Fate::Text,
            };
        }
        let place = self.space.resolve(&link);
        let got = match self.url(&place, image) {
            Ok(u) => Some(u),
            Err(e) => {
                self.dropped.push(format!("{e:#}"));
                None
            }
        };
        self.seen.insert(key, got.clone());
        match got {
            Some(u) => Fate::Url(u),
            None => Fate::Text,
        }
    }

    /// One release's section: its heading, then its text with every link
    /// written for a reader off the farm.
    fn section(&mut self, farm: &Farm, repo: &Path, r: &Release) -> Result<String> {
        let (text, dok_path) = match &r.source {
            Source::Dok(d) => (shape(&d.body), Some(d.path.clone())),
            Source::Range(range) => {
                if self.tasks.is_none() {
                    self.tasks = Some(store::load(farm.root(), &crate::farm::EVERY)?);
                }
                let tasks = self.tasks.as_deref().unwrap_or_default();
                let report: Report = report_in(tasks, &self.space, repo, range.clone())?;
                let text = entries(&report)
                    .map(|e| shape(&e))
                    .unwrap_or_else(|| "No change lines recorded.".into());
                (text, None)
            }
        };
        let text = rewrite_links(&text, |dest, image| {
            let from = match &dok_path {
                Some(p) => links::From::Dok(p),
                None => links::From::Cli,
            };
            self.fate(dest, image, from)
        });
        Ok(if text.is_empty() {
            format!("{}\n", r.heading)
        } else {
            format!("{}\n\n{text}\n", r.heading)
        })
    }
}

/// Run `yaks release changelog` from `cwd`: print the file (or write it to
/// `out`), or with `only` just that release's section, no header.
pub fn cli(farm: &Farm, cwd: &Path, out: Option<&Path>, only: Option<&str>) -> Result<()> {
    let Some(repo) = farm.code_repo(cwd) else {
        bail!(
            "release changelog reads the releases of the code repository: run it in your checkout"
        );
    };
    let releases = plan(farm, &repo, only)?;
    let mut cx = Cx::new(farm, &repo);
    let text = match only {
        Some(v) => {
            let Some(r) = releases.iter().find(|r| r.name.eq_ignore_ascii_case(v)) else {
                let mut names: Vec<String> = plan_names(farm, &repo)?;
                names.dedup();
                let names: Vec<&str> = names.iter().map(String::as_str).collect();
                bail!(
                    "{v}: not a release this branch reaches (it has: {})",
                    if names.is_empty() {
                        "none".to_string()
                    } else {
                        names.join(", ")
                    }
                );
            };
            cx.section(farm, &repo, r)?
        }
        None => {
            let mut text = HEADER.to_string();
            for r in &releases {
                text.push('\n');
                text.push_str(&cx.section(farm, &repo, r)?);
            }
            text
        }
    };
    if !cx.dropped.is_empty() {
        eprintln!(
            "note: {} link{} written as plain text: {}",
            cx.dropped.len(),
            if cx.dropped.len() == 1 { "" } else { "s" },
            cx.dropped[0]
        );
    }
    if !cx.leads_nowhere.is_empty() {
        eprintln!(
            "note: {} link{} lead nowhere until pushed: {}",
            cx.leads_nowhere.len(),
            if cx.leads_nowhere.len() == 1 { "" } else { "s" },
            cx.leads_nowhere[0]
        );
    }
    match out {
        Some(file) => {
            let path = cwd.join(file);
            std::fs::write(&path, &text)
                .map_err(|e| anyhow::anyhow!("writing {}: {e}", path.display()))?;
            println!(
                "Wrote {} ({} release{})",
                file.display(),
                if only.is_some() { 1 } else { releases.len() },
                if only.is_some() || releases.len() == 1 {
                    ""
                } else {
                    "s"
                }
            );
        }
        None => print!("{text}"),
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_dok_body_loses_its_title_markers_and_placeholder_and_demotes_headings() {
        let body = format!(
            "\n# yaks v1\n\n<!-- Headlines: what matters. -->\n\nProse.\n\n{BLOCK_START}\n\n## Added\n\n- x\n\n### Deep\n\n```\n## not a heading\n```\n\n{BLOCK_END}\n"
        );
        assert_eq!(
            shape(&body),
            "Prose.\n\n### Added\n\n- x\n\n#### Deep\n\n```\n## not a heading\n```"
        );
        // A heading is never lifted above the release's own `##`.
        assert_eq!(shape("# a\n\n# b\n"), "### b");
    }

    #[test]
    fn links_are_replaced_dropped_to_text_or_kept() {
        let text = "[a](/x) and [b](keep) ![alt](pic.png \"t\") `[c](/x)`\n";
        let out = rewrite_links(text, |dest, image| match (dest, image) {
            ("/x", false) => Fate::Url("https://h/x".into()),
            ("pic.png", true) => Fate::Text,
            _ => Fate::Keep,
        });
        assert_eq!(out, "[a](https://h/x) and [b](keep) alt `[c](/x)`\n");
    }

    #[test]
    fn version_keys_order_numbers_not_text() {
        assert!(version_key("v0.0.41") > version_key("v0.0.9"));
    }
}

/// A dok body (or generated entries) as a changelog section's text: the
/// leading `# title` line, the block markers and the headline placeholder
/// gone, every heading one level down (never above `###`, which is where a
/// release's own headings sit under its `##`), runs of blank lines collapsed.
/// Fenced code is left as written.
fn shape(text: &str) -> String {
    let mut owned: Vec<String> = Vec::new();
    // Lines are pushed as indexes so a demoted heading can be an owned string.
    enum Ln<'a> {
        Keep(&'a str),
        Own(usize),
    }
    let mut lines: Vec<Ln> = Vec::new();
    let mut fence: Option<char> = None;
    let mut content = false;
    for line in text.lines() {
        let t = line.trim();
        if let Some(marker) = fence {
            if t.starts_with(&marker.to_string().repeat(3)) {
                fence = None;
            }
            lines.push(Ln::Keep(line));
            continue;
        }
        if t.starts_with("```") || t.starts_with("~~~") {
            fence = t.chars().next();
            content = true;
            lines.push(Ln::Keep(line));
            continue;
        }
        if t == BLOCK_START
            || t == BLOCK_END
            || (t.starts_with("<!-- Headlines:") && t.ends_with("-->"))
        {
            continue;
        }
        if !content && t.starts_with("# ") {
            content = true;
            continue;
        }
        if !t.is_empty() {
            content = true;
        }
        let indent = line.len() - line.trim_start().len();
        let hashes = line.trim_start().bytes().take_while(|&b| b == b'#').count();
        let is_heading = indent <= 3
            && (1..=6).contains(&hashes)
            && line.trim_start()[hashes..].starts_with(' ');
        if is_heading {
            let level = (hashes + 1).clamp(3, 6);
            owned.push(format!(
                "{}{} {}",
                " ".repeat(indent),
                "#".repeat(level),
                line.trim_start()[hashes..].trim_start()
            ));
            lines.push(Ln::Own(owned.len() - 1));
        } else {
            lines.push(Ln::Keep(line));
        }
    }
    let mut prev_blank = true;
    let mut res = String::new();
    let mut fenced = false;
    for l in &lines {
        let s = match l {
            Ln::Keep(s) => *s,
            Ln::Own(i) => owned[*i].as_str(),
        };
        let t = s.trim();
        if t.starts_with("```") || t.starts_with("~~~") {
            fenced = !fenced;
        }
        let blank = t.is_empty() && !fenced;
        if blank && prev_blank {
            continue;
        }
        prev_blank = blank;
        res.push_str(s);
        res.push('\n');
    }
    res.trim_end().to_string()
}

/// What to do with one link or image of a section.
enum Fate {
    Keep,
    Url(String),
    /// Written as its text (an image as its alt text).
    Text,
}

/// `text` with each inline link and image sent through `fate`: a new URL
/// replaces its destination, and `Text` replaces the whole link with its
/// label. Code spans and blocks are not links.
fn rewrite_links(text: &str, mut fate: impl FnMut(&str, bool) -> Fate) -> String {
    // (start, end, replacement); a link inside a link that became text is
    // dropped from the edits.
    let mut edits: Vec<(usize, usize, String)> = Vec::new();
    for (e, r) in Parser::new_ext(text, markdown_lint::options()).into_offset_iter() {
        let (dest, image) = match &e {
            Event::Start(Tag::Link {
                dest_url,
                link_type: LinkType::Inline,
                ..
            }) => (dest_url.to_string(), false),
            Event::Start(Tag::Image {
                dest_url,
                link_type: LinkType::Inline,
                ..
            }) => (dest_url.to_string(), true),
            _ => continue,
        };
        let src = &text[r.clone()];
        let Some(open) = src.rfind("](") else {
            continue;
        };
        match fate(&dest, image) {
            Fate::Keep => {}
            Fate::Url(url) => {
                let from = r.start + open + 2;
                if let Some(at) = text[from..r.end].find(dest.as_str()) {
                    edits.push((from + at, from + at + dest.len(), url));
                }
            }
            Fate::Text => {
                let label = &src[if image { 2 } else { 1 }..open];
                edits.push((r.start, r.end, label.to_string()));
            }
        }
    }
    edits.sort_by(|a, b| a.0.cmp(&b.0).then(b.1.cmp(&a.1)));
    let mut kept: Vec<(usize, usize, String)> = Vec::new();
    for e in edits {
        if kept.last().is_some_and(|k| e.0 < k.1) {
            continue;
        }
        kept.push(e);
    }
    let mut out = text.to_string();
    for (a, b, s) in kept.into_iter().rev() {
        out.replace_range(a..b, &s);
    }
    out
}


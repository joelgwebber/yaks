const HEADER: &str = "# Changelog\n\nGenerated by `yaks release changelog` from the farm's release doks; the format follows [Keep a Changelog](https://keepachangelog.com/en/1.1.0/).\n";

/// What a release's text comes from.
enum Source {
    /// Its release dok.
    Dok(Dok),
    /// No dok: the entries of this range, computed now.
    Range(Range),
}

/// One section of the file.
struct Release {
    /// What `--release` names it by: the version, or `Unreleased`.
    name: String,
    /// The `## ` line.
    heading: String,
    source: Source,
}

/// The release tags `HEAD` reaches, newest version first. Version order, not
/// date: a tag's date is its commit's (or when it was cut), which a backport
/// branch or a late tag breaks; `versionsort.suffix=-` puts `v1.0.0-rc1`
/// before `v1.0.0`.
fn reachable_tags(repo: &Path) -> Result<Vec<String>> {
    let glob = tag_glob(repo);
    let out = git(
        repo,
        &[
            "-c",
            "versionsort.suffix=-",
            "tag",
            "--merged",
            "HEAD",
            "--list",
            &glob,
            "--sort=-v:refname",
        ],
    )?;
    if !out.status.success() {
        bail!(
            "git tag --merged HEAD failed: {}",
            String::from_utf8_lossy(&out.stderr).trim()
        );
    }
    Ok(String::from_utf8_lossy(&out.stdout)
        .lines()
        .map(str::trim)
        .filter(|l| !l.is_empty())
        .map(String::from)
        .collect())
}

/// The digits of a version, for choosing the newest of several.
fn version_key(v: &str) -> Vec<u64> {
    v.split(|c: char| !c.is_ascii_digit())
        .filter_map(|s| s.parse().ok())
        .collect()
}

/// The release dok of a version not tagged yet whose range ends at `HEAD`:
/// the release about to be cut. The newest when there are several.
fn untagged_dok(farm: &Farm, repo: &Path) -> Option<Dok> {
    let mut found: Vec<(String, Dok)> = Vec::new();
    for path in doks::dok_paths(farm.root()) {
        if !path.starts_with("doks/releases/") {
            continue;
        }
        let Some(dok) = farm.dok(&path).ok().flatten() else {
            continue;
        };
        if dok.kind() != DOK_KIND {
            continue;
        }
        let version = version_of(&dok);
        let to = dok
            .str_field("range")
            .and_then(|r| r.rsplit_once("..").map(|(_, to)| to.to_string()));
        if !tag_exists(repo, &version) && to.is_some_and(|t| t.is_empty() || t == "HEAD") {
            found.push((version, dok));
        }
    }
    found.sort_by_key(|(v, _)| version_key(v));
    found.pop().map(|(_, d)| d)
}

/// A release dok's version: its `version:`, else its file's name.
fn version_of(dok: &Dok) -> String {
    dok.str_field("version").unwrap_or_else(|| {
        let stem = dok.path.rsplit('/').next().unwrap_or(&dok.path);
        stem.strip_suffix(".md").unwrap_or(stem).to_string()
    })
}

fn commit_count(repo: &Path, range: &Range) -> usize {
    git(
        repo,
        &["rev-list", "--count", "--no-merges", &range.spec(), "--"],
    )
    .ok()
    .filter(|o| o.status.success())
    .and_then(|o| String::from_utf8_lossy(&o.stdout).trim().parse().ok())
    .unwrap_or(0)
}

/// Every section of the file, newest first; with `only`, just the section of
/// that name (the others' ranges and dates are never computed, so `--release`
/// costs one release, not the whole history). An unknown `only` gives none.
fn plan(farm: &Farm, repo: &Path, only: Option<&str>) -> Result<Vec<Release>> {
    let wanted = |name: &str| only.is_none_or(|o| o.eq_ignore_ascii_case(name));
    let zone = farm.zone();
    let tags = reachable_tags(repo)?;
    let mut out = Vec::new();
    if let Some(dok) = untagged_dok(farm, repo) {
        let v = version_of(&dok);
        if wanted(&v) {
            // The release being cut: its dok's date, so the CHANGELOG.md
            // committed with the bump (before the tag can exist) is already
            // right; `Unreleased` only when the dok has none.
            let date = dok.str_field("date").unwrap_or_else(|| "Unreleased".into());
            out.push(Release {
                heading: format!("## [{v}] - {date}"),
                name: v,
                source: Source::Dok(dok),
            });
        }
    } else if wanted("Unreleased") {
        let range = resolve_range(repo, None)?;
        if commit_count(repo, &range) > 0 {
            out.push(Release {
                name: "Unreleased".into(),
                heading: "## [Unreleased]".into(),
                source: Source::Range(range),
            });
        }
    }
    for tag in tags {
        if !wanted(&tag) {
            continue;
        }
        let dok = (doks::path_problem(&dok_path(&tag)).is_none())
            .then(|| farm.dok(&dok_path(&tag)).ok().flatten())
            .flatten()
            .filter(|d| d.kind() == DOK_KIND);
        let date = commit_day(repo, &tag, zone)
            .or_else(|| dok.as_ref().and_then(|d| d.str_field("date")))
            .map(|d| format!(" - {d}"))
            .unwrap_or_default();
        let yanked = dok
            .as_ref()
            .is_some_and(|d| d.str_field("yanked").as_deref() == Some("true"));
        out.push(Release {
            heading: format!("## [{tag}]{date}{}", if yanked { " [YANKED]" } else { "" }),
            source: match dok {
                Some(d) => Source::Dok(d),
                None => Source::Range(resolve_range(repo, Some(&tag))?),
            },
            name: tag,
        });
    }
    Ok(out)
}

/// The names `--release` accepts, newest first, without computing any range:
/// for the message when it names none of them.
fn plan_names(farm: &Farm, repo: &Path) -> Result<Vec<String>> {
    let mut names = Vec::new();
    match untagged_dok(farm, repo) {
        Some(dok) => names.push(version_of(&dok)),
        None => names.push("Unreleased".into()),
    }
    names.extend(reachable_tags(repo)?);
    Ok(names)
}

